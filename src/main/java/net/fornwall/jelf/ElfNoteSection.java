package net.fornwall.jelf;

import java.nio.ByteBuffer;
import java.nio.ByteOrder;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;

public class ElfNoteSection extends ElfSection {

    /**
     * A possible value of the {@link #n_type} where the description should contain {@link GnuAbiDescriptor}.
     * <p>
     * Note types are specific to the note owner, so this value only has this meaning in a note with the
     * "GNU" name - it is for example NT_PRSTATUS in a note owned by "CORE".
     */
    public static final int NT_GNU_ABI_TAG = 1;
    /**
     * A possible value of the {@link #n_type} for a note containing synthetic hwcap information.
     * <p>
     * The descriptor begins with two words:
     * word 0: number of entries
     * word 1: bitmask of enabled entries
     * Then follow variable-length entries, one byte followed by a '\0'-terminated hwcap name string.  The byte gives the bit
     * number to test if enabled, <code>(1U &lt;&lt; bit) &amp; bitmask</code>.
     */
    public static final int NT_GNU_HWCAP = 2;
    /**
     * A possible value of the {@link #n_type} for a note containing build ID bits as generated by "ld --build-id".
     * <p>
     * The descriptor consists of any nonzero number of bytes.
     */
    public static final int NT_GNU_BUILD_ID = 3;

    /**
     * A possible value of the {@link #n_type} for a note containing a version string generated by GNU gold.
     */
    public static final int NT_GNU_GOLD_VERSION = 4;

    /**
     * The descriptor content of a link {@link #NT_GNU_ABI_TAG} type note.
     * <p>
     * Accessible in {@link #descriptorAsGnuAbi()}.
     */
    public static final class GnuAbiDescriptor {

        /**
         * A possible value of {@link #operatingSystem}.
         */
        public static final int ELF_NOTE_OS_LINUX = 0;
        /**
         * A possible value of {@link #operatingSystem}.
         */
        public static final int ELF_NOTE_OS_GNU = 1;
        /**
         * A possible value of {@link #operatingSystem}.
         */
        public static final int ELF_NOTE_OS_SOLARIS2 = 2;
        /**
         * A possible value of {@link #operatingSystem}.
         */
        public static final int ELF_NOTE_OS_FREEBSD = 3;
        /**
         * A possible value of {@link #operatingSystem}.
         */
        public static final int ELF_NOTE_OS_KNETBSD = 4;

        /**
         * One of the ELF_NOTE_OS_* constants in this class.
         */
        public final long operatingSystem;
        /**
         * Major version of the required ABI.
         */
        public final long majorVersion;
        /**
         * Minor version of the required ABI.
         */
        public final long minorVersion;
        /**
         * Subminor version of the required ABI.
         */
        public final long subminorVersion;

        public GnuAbiDescriptor(long operatingSystem, long majorVersion, long minorVersion, long subminorVersion) {
            this.operatingSystem = operatingSystem;
            this.majorVersion = majorVersion;
            this.minorVersion = minorVersion;
            this.subminorVersion = subminorVersion;
        }

        public GnuAbiDescriptor(int operatingSystem, int majorVersion, int minorVersion, int subminorVersion) {
            this(
                    Integer.toUnsignedLong(operatingSystem),
                    Integer.toUnsignedLong(majorVersion),
                    Integer.toUnsignedLong(minorVersion),
                    Integer.toUnsignedLong(subminorVersion));
        }

        @Override
        public boolean equals(Object o) {
            if (o == null || getClass() != o.getClass()) {
                return false;
            }

            GnuAbiDescriptor that = (GnuAbiDescriptor) o;
            return operatingSystem == that.operatingSystem
                    && majorVersion == that.majorVersion
                    && minorVersion == that.minorVersion
                    && subminorVersion == that.subminorVersion;
        }

        @Override
        public int hashCode() {
            return Objects.hash(operatingSystem, majorVersion, minorVersion, subminorVersion);
        }
    }

    public static final class ElfNote {
        public final String name;

        public final long namesz;

        public final long type;

        private final byte[] descriptorBytes;

        public final byte ei_data;

        ElfNote(String name, long namesz, long type, byte[] descriptorBytes, byte ei_data) {
            this.name = name;
            this.namesz = namesz;
            this.type = type;
            this.descriptorBytes = descriptorBytes;
            this.ei_data = ei_data;
        }

        public byte[] descriptorBytes() {
            return descriptorBytes.clone();
        }

        public String descriptorAsString() {
            return new String(descriptorBytes);
        }

        /**
         * The descriptor of this note interpreted as a {@link GnuAbiDescriptor}, or null if this is not a
         * {@link #NT_GNU_ABI_TAG} note of the "GNU" owner, or if its descriptor is too small to contain one.
         */
        public GnuAbiDescriptor descriptorAsGnuAbi() {
            return gnuAbiDescriptorFrom(name, type, descriptorBytes, ei_data);
        }

        @Override
        public boolean equals(Object o) {
            if (o == null || getClass() != o.getClass()) {
                return false;
            }

            ElfNote note = (ElfNote) o;
            return type == note.type
                    && ei_data == note.ei_data
                    && Objects.equals(name, note.name)
                    && Objects.deepEquals(descriptorBytes, note.descriptorBytes);
        }

        @Override
        public int hashCode() {
            return Objects.hash(name, type, Arrays.hashCode(descriptorBytes), ei_data);
        }
    }

    static final int NHDR_SIZE = 3 * Integer.BYTES;

    /**
     * The size of the descriptor of a {@link #NT_GNU_ABI_TAG} note, which consists of four words.
     */
    static final int GNU_ABI_DESCRIPTOR_SIZE = 4 * Integer.BYTES;

    /**
     * The descriptor of the specified note interpreted as a {@link #NT_GNU_ABI_TAG} one, or null if the
     * note is not a GNU ABI tag note or if its descriptor is too small to contain one.
     */
    private static GnuAbiDescriptor gnuAbiDescriptorFrom(String name, long type, byte[] descriptorBytes, byte ei_data) {
        if (type != NT_GNU_ABI_TAG
                || !ElfNoteTypes.ELF_NOTE_GNU.equals(name)
                || descriptorBytes.length < GNU_ABI_DESCRIPTOR_SIZE) {
            return null;
        }

        ByteBuffer buffer = ByteBuffer.wrap(descriptorBytes)
                .order(ei_data == ElfFile.DATA_LSB ? ByteOrder.LITTLE_ENDIAN : ByteOrder.BIG_ENDIAN);
        return new GnuAbiDescriptor(buffer.getInt(0), buffer.getInt(4), buffer.getInt(8), buffer.getInt(12));
    }

    public final /* uint32_t */ long n_namesz;
    public final /* uint32_t */ long n_descsz;
    public final /* uint32_t */ long n_type;
    private final String n_name;
    private final byte[] descriptorBytes;
    private final GnuAbiDescriptor gnuAbiDescriptor;

    ElfNoteSection(ElfParser parser, ElfSectionHeader header) throws ElfException {
        super(parser, header);

        parser.seek(header.sh_offset);
        n_namesz = parser.readUnsignedInt();
        n_descsz = parser.readUnsignedInt();
        n_type = parser.readUnsignedInt();
        long pos = NHDR_SIZE;

        if (n_namesz > Integer.MAX_VALUE || n_namesz > header.sh_size - pos) {
            throw new ElfException("Invalid note namesz: " + n_namesz);
        }

        int nameSize = (int) n_namesz;
        byte[] nameBytes = new byte[nameSize];
        int bytesRead = parser.read(nameBytes);

        if (bytesRead != nameSize) {
            throw new ElfException("Error reading note name (read=" + bytesRead + ", expected=" + n_namesz + ")");
        }

        long namePos = header.sh_offset + NHDR_SIZE;
        long align = header.sh_addralign;
        long alignedNameEnd = align == Long.BYTES ? noteAlign8(namePos + n_namesz) : noteAlign4(namePos + n_namesz);
        parser.skip((int) (alignedNameEnd - namePos - n_namesz));
        pos = alignedNameEnd - header.sh_offset;

        if (n_descsz > Integer.MAX_VALUE || n_descsz > header.sh_size - pos) {
            throw new ElfException("Invalid note descsz: " + n_descsz);
        }

        int descriptorSize = (int) n_descsz;
        descriptorBytes = new byte[descriptorSize];
        bytesRead = parser.read(descriptorBytes);

        if (bytesRead != descriptorSize) {
            throw new ElfException("Error reading note descriptor (read=" + bytesRead + ", expected=" + n_descsz + ")");
        }

        int nameLen = 0;

        while (nameLen < nameSize && nameBytes[nameLen] != 0) {
            nameLen++;
        }

        n_name = new String(nameBytes, 0, nameLen);
        gnuAbiDescriptor = gnuAbiDescriptorFrom(n_name, n_type, descriptorBytes, parser.elfFile.ei_data);
    }

    public String getName() {
        return n_name;
    }

    public byte[] descriptorBytes() {
        return descriptorBytes;
    }

    public String descriptorAsString() {
        return new String(descriptorBytes);
    }

    /**
     * The descriptor of the first note of this section interpreted as a {@link GnuAbiDescriptor}, or null if
     * that is not a {@link #NT_GNU_ABI_TAG} note of the "GNU" owner, or if its descriptor is too small.
     */
    public GnuAbiDescriptor descriptorAsGnuAbi() {
        return gnuAbiDescriptor;
    }

    static long noteAlign4(long n) {
        return (n + 3) & -4L;
    }

    static long noteAlign8(long n) {
        return (n + 7) & -8L;
    }

    public List<ElfNote> notes() {
        return readNotes(parser, header.sh_offset, header.sh_size, header.sh_addralign);
    }

    static List<ElfNote> readNotes(ElfParser parser, long offset, long size, long align) {
        parser.seek(offset);
        long pos = offset;
        long end = offset + size;
        List<ElfNote> result = new ArrayList<>();

        while (pos + NHDR_SIZE <= end) {
            long namesz = parser.readUnsignedInt();
            long descsz = parser.readUnsignedInt();
            long type = parser.readUnsignedInt();
            pos += NHDR_SIZE;

            if (namesz > Integer.MAX_VALUE) {
                throw new ElfException("Invalid note namesz: " + namesz);
            }

            if (descsz > Integer.MAX_VALUE) {
                throw new ElfException("Invalid note descsz: " + descsz);
            }

            long nameEnd = align == Long.BYTES ? noteAlign8(pos + namesz) : noteAlign4(pos + namesz);
            long descEnd = align == Long.BYTES ? noteAlign8(nameEnd + descsz) : noteAlign4(nameEnd + descsz);

            if (nameEnd < pos || descEnd < nameEnd || descEnd > end) {
                throw new ElfException("Note out of bounds (pos=" + pos + ", nameEnd=" + nameEnd + ", descEnd="
                        + descEnd + ", end=" + end + ")");
            }

            int nameSize = (int) namesz;
            byte[] nameBytes = new byte[nameSize];
            int bytesRead = parser.read(nameBytes);

            if (bytesRead != nameSize) {
                throw new ElfException("Error reading note name (read=" + bytesRead + ", expected=" + namesz + ")");
            }

            if (nameEnd > pos + namesz) {
                parser.skip((int) (nameEnd - pos - namesz));
            }

            pos = nameEnd;

            int descriptorSize = (int) descsz;
            byte[] desc = new byte[descriptorSize];
            bytesRead = parser.read(desc);

            if (bytesRead != descriptorSize) {
                throw new ElfException(
                        "Error reading note descriptor (read=" + bytesRead + ", expected=" + descsz + ")");
            }

            if (descEnd > pos + descsz) {
                parser.skip((int) (descEnd - pos - descsz));
            }

            pos = descEnd;
            int nameLen = 0;

            while (nameLen < nameSize && nameBytes[nameLen] != 0) {
                nameLen++;
            }

            String name = new String(nameBytes, 0, nameLen);
            result.add(new ElfNote(name, namesz, type, desc, parser.elfFile.ei_data));
        }

        return result;
    }

    @Override
    public boolean equals(Object o) {
        if (o == null || getClass() != o.getClass()) {
            return false;
        }

        ElfNoteSection that = (ElfNoteSection) o;
        return n_namesz == that.n_namesz
                && n_descsz == that.n_descsz
                && n_type == that.n_type
                && Objects.equals(n_name, that.n_name)
                && Objects.deepEquals(descriptorBytes, that.descriptorBytes)
                && Objects.equals(gnuAbiDescriptor, that.gnuAbiDescriptor);
    }

    @Override
    public int hashCode() {
        return Objects.hash(n_namesz, n_descsz, n_type, n_name, Arrays.hashCode(descriptorBytes), gnuAbiDescriptor);
    }
}
